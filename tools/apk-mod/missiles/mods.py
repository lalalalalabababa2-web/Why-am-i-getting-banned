#!/usr/bin/env python3
"""Missiles! (pl.macaque.Missiles) 1.41 mods for libil2cpp.so.

usage: python3 mods.py libil2cpp.so Patches.java

Checks every patch site, writes the menu's table (modmenu/Patches.java), and
writes ALWAYS_ON into the library file itself: the game's Google Play Games
leaderboards are real, so this build never uploads a score. Addresses are RVAs
from Il2CppDumper's dump.cs for this build. Needs: pip install capstone keystone-engine
"""
import sys

import capstone
import keystone

# Written into the file, not switchable.
ALWAYS_ON = [
    ("No score upload", [
        (0x12A5EC0, "stp x30, x27, [sp, #-0x50]!", "ret"),  # PlayerProfile.SubmitScores
        (0x12A68A8, "str x30, [sp, #-0x40]!", "ret"),       # PlayerProfile.UpdateLeaderboardScore
    ]),
]

# (menu label, [(address, original instruction(s), replacement)])
MODS = [
    ("God mode", [
        # Player.OnTriggerEnter2D: a missile hit always takes the "had a shield" path.
        (0x129619C, "cbz w8, #0x12961c8", "nop"),
    ]),
    ("Unlimited coins", [
        (0x12A4308, "ldr x8, [x0, #0x30]; cbz x8, #0x12a431c; ldp w8, w9, [x8, #0x38]",
         "mov w0, #0x423f; movk w0, #0xf, lsl #16; ret"),  # PlayerProfile.get_Points -> 999999
    ]),
    ("Coins x16", [
        (0x12A6F18, "add w9, w9, w1", "add w9, w9, w1, lsl #4"),  # PlayerProfile.AddCoins
    ]),
    ("Free planes", [
        (0x12A4450, "add w10, w10, w22", "nop"),  # PlayerProfile.BuyPlane: price no longer subtracted
    ]),
    ("Score x8", [
        # GameState.get_Score = stars + time + missiles + power-ups; stars and time x8.
        (0x1298824, "add w9, w22, w0", "add w9, w0, w22"),
        (0x129882C, "add w0, w8, w9", "add w0, w9, w8, lsl #3"),
    ]),
    ("Stars x10", [
        (0x129E35C, "add w1, w0, #1", "add w1, w0, #10"),  # GameState.StarCollected
    ]),
    ("Slow missiles", [
        # MissileEngine.SetAngle and MissileTargetingEngine.SetAngle: the difficulty
        # speed factor becomes a flat 0.5.
        (0x1294280, "ldr s2, [x21, #0x20]", "fmov s2, #0.5"),
        (0x129500C, "ldr s2, [x21, #0x20]", "fmov s2, #0.5"),
    ]),
    ("Fast plane", [
        # Player.UpdateInput: current speed doubled before the velocity is set.
        # Takes the slot of "mov x1, xzr", the MethodInfo argument set_velocity ignores.
        (0x1295A94, "mov x1, xzr", "fadd s2, s2, s2"),
    ]),
]

TEXT_DELTA = 0x4000  # executable segment: address - file offset

md = capstone.Cs(capstone.CS_ARCH_ARM64, capstone.CS_MODE_ARM)
ks = keystone.Ks(keystone.KS_ARCH_ARM64, keystone.KS_MODE_LITTLE_ENDIAN)


def norm(s):
    return [" ".join(i.replace(".00000000", ".0").split()) for i in s.split(";")]


def check(data, label, addr, want, new):
    enc, _ = ks.asm(new, addr)
    off = addr - TEXT_DELTA
    orig = bytes(data[off:off + len(enc)])
    have = [f"{i.mnemonic} {i.op_str}".strip() for i in md.disasm(orig, addr)]
    if norm("; ".join(have)) != norm(want):
        sys.exit(f"{label} {addr:#x}: expected {norm(want)}, found {have}. Wrong game version?")
    return off, orig, bytes(enc)


def main():
    lib, out = sys.argv[1:]
    data = bytearray(open(lib, "rb").read())
    rows = []
    for label, patches in MODS:
        sites = []
        for addr, want, new in patches:
            _, orig, enc = check(data, label, addr, want, new)
            sites.append(f'new Patch(0x{addr:X}L, "{orig.hex()}", "{enc.hex()}")')
        rows.append(f'        new Mod("{label}", new Patch[] {{\n            ' + ",\n            ".join(sites) + "}),")
    for label, patches in ALWAYS_ON:
        for addr, want, new in patches:
            off, _, enc = check(data, label, addr, want, new)
            data[off:off + len(enc)] = enc
    open(lib, "wb").write(data)
    with open(out, "w") as f:
        f.write("// Generated by tools/apk-mod/missiles/mods.py from libil2cpp.so 1.41. Do not edit.\n")
        f.write("package modmenu;\n\nfinal class Patches {\n")
        f.write('    static final String LIB = "libil2cpp.so";\n')
        f.write('    static final String TITLE = "\\u2708\\uFE0F Mods";\n')
        f.write("    static final Mod[] MODS = {\n" + "\n".join(rows) + "\n    };\n}\n")
    print(f"{sum(len(p) for _, p in MODS)} menu patch sites checked; score upload removed from {lib}")


if __name__ == "__main__":
    main()
