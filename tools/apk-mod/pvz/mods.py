#!/usr/bin/env python3
"""Plants vs. Zombies FREE (com.ea.game.pvzfree_row) 3.18.0 mods for libpvz.so.

usage: python3 mods.py libpvz.so Patches.java
       python3 mods.py libpvz.so --bake [label,label]   (writes the patches into the file)

Checks every patch site against the library and writes the table the in-game
menu uses (pvzmod/Patches.java). Addresses are virtual addresses from the
library's own symbols (nm -D -C libpvz.so). Nothing in the file is changed:
the menu writes the patches into memory while the game runs, so each mod can
be switched off again. Needs: pip install capstone keystone-engine
"""
import sys

import capstone
import keystone

# (menu label, [(address, original instruction(s), replacement)])
MODS = [
    ("Unlimited sun", [
        (0x19FA900, "sub sp, sp, #0x40; stp x29, x30, [sp, #0x30]", "mov w0, #1; ret"),  # Board::TakeSunMoney
        (0x1A12FB8, "sub sp, sp, #0x30; stp x29, x30, [sp, #0x20]", "mov w0, #1; ret"),  # Board::CanTakeSunMoney
    ]),
    ("No cooldown", [
        # Plant::GetRefreshTime: 1 rather than 0, the seed packet divides by it when drawn.
        (0x1B5B674, "sub sp, sp, #0x30; stp x29, x30, [sp, #0x20]", "mov w0, #1; ret"),
    ]),
    ("Plant anywhere", [
        (0x19F65C0, "sub sp, sp, #0x80; stp x29, x30, [sp, #0x70]", "mov w0, #0; ret"),  # Board::CanPlantAt -> PLANTING_OK
    ]),
    ("Zombies can't win", [
        (0x1A01D90, "stp x29, x30, [sp, #-0x20]!", "ret"),  # Board::ZombiesWon
    ]),
    ("One-hit kills", [
        # Zombie::TakeDamage: every read of the damage argument becomes 32767.
        (0x1C754C8, "ldur w8, [x29, #-0xc]", "mov w8, #0x7fff"),
        (0x1C754E0, "ldur w1, [x29, #-0xc]", "mov w1, #0x7fff"),
        (0x1C7552C, "ldur w1, [x29, #-0xc]", "mov w1, #0x7fff"),
        (0x1C75550, "ldur w8, [x29, #-0xc]", "mov w8, #0x7fff"),
        (0x1C75584, "ldur w1, [x29, #-0xc]", "mov w1, #0x7fff"),
    ]),
    ("Sun x4", [
        (0x1A12CA4, "add w10, w10, w12", "add w10, w10, w12, lsl #2"),  # Board::AddSunMoney
    ]),
    ("Coins x10", [
        # Coin::GetCoinValue: silver 1, gold 5, diamond 100.
        (0x1A42A10, "mov w8, #1", "mov w8, #10"),
        (0x1A42A2C, "mov w8, #5", "mov w8, #50"),
        (0x1A42A48, "mov w8, #0x64", "mov w8, #1000"),
    ]),
]

# The executable segment's file offset is 0x4000 below its address.
TEXT_DELTA = 0x4000

md = capstone.Cs(capstone.CS_ARCH_ARM64, capstone.CS_MODE_ARM)
ks = keystone.Ks(keystone.KS_ARCH_ARM64, keystone.KS_MODE_LITTLE_ENDIAN)


def norm(s):
    return [" ".join(i.split()) for i in s.split(";")]


def main():
    lib, out = sys.argv[1:3]
    bake = out == "--bake"
    only = sys.argv[3].split(",") if bake and len(sys.argv) > 3 else None
    data = bytearray(open(lib, "rb").read())
    rows = []
    for label, patches in MODS:
        if only and label not in only:
            continue
        sites = []
        for addr, want, new in patches:
            enc, _ = ks.asm(new, addr)
            off = addr - TEXT_DELTA
            orig = data[off:off + len(enc)]
            have = [f"{i.mnemonic} {i.op_str}".strip() for i in md.disasm(orig, addr)]
            if have != norm(want):
                sys.exit(f"{label} {addr:#x}: expected {norm(want)}, found {have}. Wrong game version?")
            if bake:
                data[off:off + len(enc)] = bytes(enc)
            sites.append(f'new Patch(0x{addr:X}L, "{orig.hex()}", "{bytes(enc).hex()}")')
        rows.append(f'        new Mod("{label}", new Patch[] {{\n            ' + ",\n            ".join(sites) + "}),")
    if bake:
        open(lib, "wb").write(data)
        print(f"baked {len(rows)} mods into {lib}")
        return
    with open(out, "w") as f:
        f.write("// Generated by tools/apk-mod/pvz/mods.py from libpvz.so 3.18.0. Do not edit.\n")
        f.write("package pvzmod;\n\nfinal class Patches {\n    static final Mod[] MODS = {\n")
        f.write("\n".join(rows) + "\n    };\n}\n")
    print(f"{sum(len(p) for _, p in MODS)} patch sites in {len(MODS)} mods checked")


if __name__ == "__main__":
    main()
